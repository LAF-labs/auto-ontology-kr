#!/usr/bin/env node
/**
 * Write client.js from src/ko.json. The harness serves a package's browser
 * half as one file, so the dictionaries are embedded. Run after editing
 * src/ko.json:  node ours/locale-ko/build.mjs
 *
 * src/en.snapshot.json is the English text the translation was made from: the
 * `en` dictionary of every namespace the product profile loads. To refresh it
 * after taking upstream changes, open the running product with
 * `?ours-locale-dump` in the URL and save, from the browser console,
 *   Object.fromEntries([...__OURS_LOCALE__.dicts].map(([ns, m]) => [ns, m.get('en')]).filter(([ns, en]) => en && !ns.startsWith('ours.')))
 * then translate the keys this script reports as missing. A missing key shows
 * the English text; it is reported, not an error.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { checkDictionaries, missingKeys } from './src/check.mjs'

const here = new URL('.', import.meta.url)
const dictionaries = JSON.parse(readFileSync(new URL('src/ko.json', here), 'utf8'))
const english = JSON.parse(readFileSync(new URL('src/en.snapshot.json', here), 'utf8'))
const problems = checkDictionaries(dictionaries, english)
if (problems.length > 0) {
  console.error(problems.join('\n'))
  process.exit(1)
}
const source = `/**
 * Korean language pack (generated by build.mjs from src/ko.json; edit that file).
 * Registers \`ko\` with English as its fallback, then one dictionary per
 * namespace. A key missing here shows the English text.
 */
window.__ModuleLoader__.load({
  id: '@ours/locale-ko',
  factory() {
    const DICTIONARIES = ${JSON.stringify(dictionaries, null, 2).replace(/\n/g, '\n    ')}
    return {
      inject: ['locale'],
      apply(ctx) {
        ctx.effect(() => ctx.locale.addLanguage({ id: 'ko', label: '한국어', fallback: 'en' }), 'locale-ko: language')
        for (const [ns, dict] of Object.entries(DICTIONARIES)) {
          ctx.effect(() => ctx.locale.register(ns, 'ko', dict), \`locale-ko: \${ns}\`)
        }
        // Maintenance aid for refreshing src/en.snapshot.json (see build.mjs).
        if (new URLSearchParams(location.search).has('ours-locale-dump')) globalThis.__OURS_LOCALE__ = ctx.locale
      },
    }
  },
})
`
writeFileSync(new URL('client.js', here), source)
const count = Object.values(dictionaries).reduce((n, d) => n + Object.keys(d).length, 0)
console.log(`client.js: ${Object.keys(dictionaries).length} namespaces, ${count} keys`)
const untranslated = missingKeys(dictionaries, english)
if (untranslated.length > 0) console.log(`not translated (shown in English): ${untranslated.length}\n  ${untranslated.join('\n  ')}`)
